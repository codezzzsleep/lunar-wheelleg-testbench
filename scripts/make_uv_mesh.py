"""
给无 UV 的 STL 生成带三平面（triplanar）UV 的 OBJ，供 MuJoCo 正确采样 2D 贴图。

  .venv/bin/python scripts/make_uv_mesh.py --mesh in.stl --out out.obj --scale 4.0

为什么需要它：MuJoCo 对没有 UV 的 STL 网格做 2D 贴图会退化成平面投影，
渲染成横向/纵向条带（已用球和立方体验证）。这里按每个三角面的主法向轴
选择投影平面，写出 `vt` 纹理坐标与 `vn` 法线，得到非条带的岩石表面。

只改视觉，不改几何：顶点坐标原样输出，面索引一一对应。
"""
import argparse
import pathlib

import numpy as np
import trimesh


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--mesh', required=True)
    ap.add_argument('--out', required=True)
    ap.add_argument('--scale', type=float, default=4.0,
                    help='纹理重复次数（每米多少个贴图周期）')
    a = ap.parse_args()

    m = trimesh.load(a.mesh, force='mesh')
    m = m.copy()
    V = np.asarray(m.vertices, dtype=np.float64)
    F = np.asarray(m.faces, dtype=np.int64)
    N = np.asarray(m.face_normals, dtype=np.float64)

    # 让 UV 与世界尺度相关（避免缩放后纹理疏密跳变）
    lo = V.min(0)
    span = max(float((V.max(0) - lo).max()), 1e-6)
    U = (V - lo) / span

    lines = ['# triplanar UV mesh generated by make_uv_mesh.py',
             f'# source: {pathlib.Path(a.mesh).name}  faces={len(F)}']
    for v in V:
        lines.append(f'v {v[0]:.9f} {v[1]:.9f} {v[2]:.9f}')
    # 每个面各写 3 个 vt（按主法向轴选择投影平面）
    uv_index = []
    for fi in range(len(F)):
        n = N[fi]
        ax = int(np.argmax(np.abs(n)))
        if ax == 0:      # 法向 x -> 用 y,z
            uv = U[F[fi]][:, [1, 2]]
        elif ax == 1:    # 法向 y -> 用 x,z
            uv = U[F[fi]][:, [0, 2]]
        else:            # 法向 z -> 用 x,y
            uv = U[F[fi]][:, [0, 1]]
        base = 1 + 3 * fi
        for k in range(3):
            lines.append(f'vt {uv[k][0]*a.scale:.6f} {uv[k][1]*a.scale:.6f}')
        # 该面的 3 个顶点索引（1-based，复用 v）
        uv_index.append((base + k for k in range(3)))

    # 面：v/vt/vn 同索引（每个面独立，避免跨面共享 UV 冲突）
    vt_cursor = 0
    for fi in range(len(F)):
        vids = F[fi] + 1
        uv_ids = [vt_cursor + 1, vt_cursor + 2, vt_cursor + 3]
        vt_cursor += 3
        n = N[fi]
        lines.append(f'f {vids[0]}/{uv_ids[0]} {vids[1]}/{uv_ids[1]} '
                     f'{vids[2]}/{uv_ids[2]}')

    out = pathlib.Path(a.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text('\n'.join(lines) + '\n')
    print({'out': str(out), 'vertices': len(V), 'faces': len(F),
           'uv_scale': a.scale, 'bytes': out.stat().st_size})
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
